"""Host Git identity shared read-only with the project container."""

import subprocess

GITCONFIG = "gitconfig"
KEYS = ("user.name", "user.email")


def host_git_identity(path, runner=subprocess.run) -> dict[str, str]:
    """Read the identity Git on the host would use for commits in this folder.

    Running inside the project folder honours the host's includeIf rules, so a
    work identity configured for ~/work/ also applies to its Brig projects.
    """
    identity = {}
    for key in KEYS:
        try:
            result = runner(
                ["git", "-C", str(path), "config", "--get", key],
                capture_output=True,
                text=True,
                check=False,
            )
        except OSError:
            return {}
        value = (result.stdout or "").strip() if result.returncode == 0 else ""
        # A newline would end the gitconfig entry and inject further settings.
        if value and "\n" not in value and "\0" not in value:
            identity[key] = value
    return identity


def render_gitconfig(identity) -> str:
    lines = ["# Generated by Brig from the host Git identity; read-only.\n"]
    if identity:
        lines.append("[user]\n")
        for key, value in sorted(identity.items()):
            escaped = value.replace("\\", "\\\\").replace('"', '\\"')
            lines.append(f'\t{key.split(".", 1)[1]} = "{escaped}"\n')
    return "".join(lines)
