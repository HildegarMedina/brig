"""Render development Dockerfiles from pinned project configurations."""

import json
import shlex

from brig.components.agents import AGENTS, validate_agents
from brig.components.catalog import validate_selection
from brig.docker.auth_proxy import proxy_image_lines
from brig.docker.isolation import agent_config, agent_home, bootstrap_script
from brig.docker.tools import AGENT_TOOLS
from brig.errors import BrigError
from brig.i18n import tr
from brig.models import Project

# Runtime builders can be extended without changing the CLI or application.
DATABASE_DRIVERS = {
    "mysql": ("pdo_mysql", ()),
    "mariadb": ("pdo_mysql", ()),
    "postgresql": ("pdo_pgsql", ("libpq-dev",)),
}

DATABASE_CLIENTS = {
    "postgresql": ("postgresql-client",),
    "mysql": ("default-mysql-client",),
    "mariadb": ("default-mysql-client",),
    "redis": ("redis-tools",),
}

# Every runtime uses the same Debian release, including in mixed profiles.
RUNTIME_IMAGES = {
    "php": "php:{version}-cli-bookworm",
    "python": "python:{version}-bookworm",
    "node": "node:{version}-bookworm",
    "go": "golang:{version}-bookworm",
    "rust": "rust:{version}-bookworm",
    # Temurin images are Ubuntu-based; only the self-contained JDK is copied.
    "java": "eclipse-temurin:{version}-jdk",
}

# Toolchains copied from their official images into the shared Debian stage.
# Package caches stay in each user's home (GOPATH, CARGO_HOME, ~/.m2, ~/.gradle).
TOOLCHAINS = {
    "go": (
        ("/usr/local/go/", "/opt/go/"),
        ("GOTOOLCHAIN=local", "PATH=/opt/go/bin:$PATH"),
    ),
    "rust": (
        ("/usr/local/rustup/", "/opt/rust/rustup/"),
        ("/usr/local/cargo/bin/", "/opt/rust/bin/"),
        ("RUSTUP_HOME=/opt/rust/rustup", "PATH=/opt/rust/bin:$PATH"),
    ),
    "java": (
        ("/opt/java/openjdk/", "/opt/java/openjdk/"),
        ("JAVA_HOME=/opt/java/openjdk", "PATH=/opt/java/openjdk/bin:$PATH"),
    ),
}

# Commands run in a toolchain's own stage before it is copied.
TOOLCHAIN_SETUP = {
    # The official image installs rustup's minimal profile.
    "rust": "RUN rustup component add clippy rustfmt",
}

# Build tools are pure Java distributions; each image tag pairs one with a JDK.
JAVA_TOOLS = {
    "maven": (
        "maven:{version}-eclipse-temurin-{java}",
        "/usr/share/maven/",
        "/opt/maven/",
        ("MAVEN_HOME=/opt/maven", "PATH=/opt/maven/bin:$PATH"),
    ),
    "gradle": (
        "gradle:{version}-jdk{java}",
        "/opt/gradle/",
        "/opt/gradle/",
        ("GRADLE_HOME=/opt/gradle", "PATH=/opt/gradle/bin:$PATH"),
    ),
}

# Native linkers and build helpers for cgo and Rust crates.
NATIVE_BUILD_PACKAGES = ("g++", "gcc", "libc6-dev", "make", "pkg-config")


def python_stage(version: str) -> list[str]:
    return [
        f"FROM {RUNTIME_IMAGES['python'].format(version=version)} AS python_runtime",
        # Discover dependencies from the selected image, rather than keeping a
        # library list that becomes stale as Python gains optional modules.
        "RUN set -eu; \\",
        "    find /usr/local -type f \\( -executable -o -name '*.so' \\) -exec ldd '{}' ';' 2>/dev/null \\",
        # dpkg may register /usr/lib while ldd returns /lib on merged-/usr
        # systems. Match the suffix as the official Python image does.
        '    | awk \'/=> \\// { so = $(NF-1); if (index(so, "/usr/local/") == 1) next; sub("^/(usr/)?", "", so); print "*" so }\' \\\n    | sort -u > /tmp/brig-python-libraries; \\',
        "    test -s /tmp/brig-python-libraries; \\",
        "    xargs dpkg-query --search < /tmp/brig-python-libraries > /tmp/brig-python-owners; \\",
        '    awk \'sub(":$", "", $1) { print $1 }\' /tmp/brig-python-owners | sort -u > /brig-python-packages; \\',
        "    test -s /brig-python-packages; \\",
        "    rm /tmp/brig-python-libraries /tmp/brig-python-owners",
        "",
    ]


def render_dockerfile(project: Project) -> str:
    configuration = project.configuration
    validate_agents(configuration.selected_agents, configuration.agent)
    validate_selection(
        configuration.runtimes,
        configuration.tools,
        configuration.services,
        configuration.agent,
    )
    unsupported = set(configuration.runtimes) - RUNTIME_IMAGES.keys()
    if unsupported:
        raise BrigError(
            tr("No Dockerfile builder for: {value0}.").format(
                value0=", ".join(sorted(unsupported))
            )
        )
    if type(configuration.number) is not int or configuration.number < 1:
        raise BrigError(
            tr("Cannot generate a Dockerfile from an invalid profile version.")
        )

    integrations = [AGENTS[name] for name in sorted(configuration.selected_agents)]
    lines = [
        "# Generated by Brig from the project's pinned profile version.",
        "# Development image; the project directory is mounted at /workspace at runtime.",
        "# Database containers are configured separately.",
    ]
    lines.extend(runtime_lines(configuration, integrations))
    lines.extend(database_client_lines(configuration))
    lines.extend(tool_lines(configuration))
    lines.extend(user_lines(configuration.tools.get("composer")))
    lines.extend(
        [
            f"LABEL org.brig.project={json.dumps(project.name)} \\",
            f"      org.brig.profile={json.dumps(project.profile)} \\",
            f"      org.brig.profile.version={json.dumps(str(configuration.number))}",
            "",
            "WORKDIR /workspace",
            "USER brig",
            'CMD ["sleep", "infinity"]',
        ]
    )
    lines.extend(proxy_image_lines())
    lines.extend(
        [
            "FROM development AS dev",
            "USER root",
            "ARG BRIG_UID=1000",
            "ARG BRIG_GID=1000",
        ]
    )
    for name in sorted(configuration.selected_agents):
        integration = AGENTS[name]
        lines.extend(integration.image)
        offset = 10000 + sorted(AGENTS).index(name)
        home, config = agent_home(name), agent_config(name)
        paths = [home, f"{home}/.local/state"]
        if config:
            paths.extend(
                [
                    config,
                    *[
                        f"{config}/{history}"
                        for history in integration.history_directories
                    ],
                ]
            )
        lines.extend(
            [
                f'RUN agent_uid=$((BRIG_UID + {offset})); useradd --uid "$agent_uid" --gid brig --home-dir {home} --shell /bin/bash brig-agent-{name} && \\',
                f'    mkdir -p {" ".join(paths)} && chown -R "$agent_uid:$BRIG_GID" {home} && chmod 700 {" ".join(paths)}',
            ]
        )
    script = bootstrap_script(
        configuration.selected_agents,
        configuration.services,
        configuration.runtimes,
        configuration.tools,
    )
    lines.extend(
        [
            "RUN mkdir -p /usr/local/lib/brig && printf '%s\\n' "
            + " ".join(shlex.quote(line) for line in script.splitlines())
            + " > /usr/local/lib/brig/bootstrap.sh && chmod 755 /usr/local/lib/brig/bootstrap.sh",
            'ENTRYPOINT ["/usr/local/lib/brig/bootstrap.sh"]',
            "",
        ]
    )
    return "\n".join(lines) + "\n"


def system_packages(configuration, integrations):
    php = configuration.runtimes.get("php")
    node = configuration.runtimes.get("node")
    packages = {
        "ca-certificates",
        "git",
        "unzip",
        "curl",
        "jq",
        "ripgrep",
        "iptables",
        "acl",
        "util-linux",
        *AGENT_TOOLS,
    }
    for service in configuration.services:
        packages.update(DATABASE_CLIENTS.get(service, ()))
    if "mongodb" in configuration.services:
        packages.add("gnupg")
    for integration in integrations:
        packages.update(integration.packages)
    extensions = set()
    if php:
        packages.update({"libicu-dev", "libzip-dev"})
        extensions.update({"bcmath", "intl", "pcntl", "zip"})
        for service in configuration.services:
            if service in DATABASE_DRIVERS:
                driver, required_packages = DATABASE_DRIVERS[service]
                extensions.add(driver)
                packages.update(required_packages)
    if node:
        packages.update({"libstdc++6", "libatomic1"})
    if "go" in configuration.runtimes or "rust" in configuration.runtimes:
        packages.update(NATIVE_BUILD_PACKAGES)
    if "java" in configuration.runtimes:
        packages.add("fontconfig")
    return packages, extensions


def runtime_lines(configuration, integrations) -> list[str]:
    runtimes = configuration.runtimes
    php = runtimes.get("php")
    python = runtimes.get("python")
    node = runtimes.get("node")
    composer = configuration.tools.get("composer")
    packages, extensions = system_packages(configuration, integrations)
    lines = []
    for integration in integrations:
        lines.extend(integration.stage)
    if composer:
        lines.extend([f"FROM composer:{composer} AS composer_binary", ""])
    if python and php:
        lines.extend(python_stage(python))
    if node:
        lines.extend(
            [f"FROM {RUNTIME_IMAGES['node'].format(version=node)} AS node_runtime", ""]
        )
    for name in sorted(TOOLCHAINS.keys() & runtimes.keys()):
        image = RUNTIME_IMAGES[name].format(version=runtimes[name])
        lines.append(f"FROM {image} AS {name}_runtime")
        if name in TOOLCHAIN_SETUP:
            lines.append(TOOLCHAIN_SETUP[name])
        lines.append("")
    for name in sorted(JAVA_TOOLS.keys() & configuration.tools.keys()):
        image = JAVA_TOOLS[name][0].format(
            version=configuration.tools[name], java=runtimes["java"]
        )
        lines.extend([f"FROM {image} AS {name}_binary", ""])
    base = (
        RUNTIME_IMAGES["php"].format(version=php)
        if php
        else RUNTIME_IMAGES["python"].format(version=python)
        if python
        else "debian:bookworm-slim"
    )
    lines.extend(
        [
            f"FROM {base} AS development",
            "",
            "ARG BRIG_UID=1000",
            "ARG BRIG_GID=1000",
            "",
        ]
    )
    if python and php:
        lines.extend(
            [
                "COPY --from=python_runtime /usr/local/ /opt/python/",
                "COPY --from=python_runtime /brig-python-packages /tmp/brig-python-packages",
                "ENV PATH=/opt/python/bin:$PATH",
                "",
            ]
        )
    if node:
        lines.extend(
            [
                "COPY --from=node_runtime /usr/local/ /opt/node/",
                "ENV PATH=/opt/node/bin:$PATH",
                "ENV NPM_CONFIG_PREFIX=/opt/node",
                "",
            ]
        )
    for name in sorted(TOOLCHAINS.keys() & runtimes.keys()):
        *copies, environment = TOOLCHAINS[name]
        for source, target in copies:
            lines.append(f"COPY --from={name}_runtime {source} {target}")
        lines.extend([f"ENV {value}" for value in environment] + [""])
    lines.extend(
        [
            "RUN set -eux; \\",
            "    apt-get update; \\",
            f"    apt-get install -y --no-install-recommends {' '.join(sorted(packages))}; \\",
            # Debian names the fd binary fdfind; agents expect fd.
            "    ln -s /usr/bin/fdfind /usr/local/bin/fd; \\",
        ]
    )
    if python and php:
        lines.extend(
            [
                "    xargs -r apt-get install -y --no-install-recommends < /tmp/brig-python-packages; \\",
                "    rm /tmp/brig-python-packages; \\",
                "    echo /opt/python/lib > /etc/ld.so.conf.d/brig-python.conf; \\",
                "    ldconfig; \\",
            ]
        )
    if php:
        lines.append(
            f'    docker-php-ext-install -j"$(nproc)" {" ".join(sorted(extensions))}; \\'
        )
    lines.extend(["    rm -rf /var/lib/apt/lists/*", ""])
    return lines


def database_client_lines(configuration) -> list[str]:
    lines = []
    if "mongodb" in configuration.services:
        lines.extend(
            [
                "# MongoDB's shell is distributed separately from the selected server.",
                "RUN set -eux; \\",
                "    curl -fsSL https://pgp.mongodb.com/server-8.0.asc -o /tmp/mongodb.asc; \\",
                "    gpg --dearmor -o /usr/share/keyrings/mongodb-shell.gpg /tmp/mongodb.asc; \\",
                "    echo 'deb [signed-by=/usr/share/keyrings/mongodb-shell.gpg] https://repo.mongodb.org/apt/debian bookworm/mongodb-org/8.0 main' > /etc/apt/sources.list.d/mongodb-shell.list; \\",
                "    apt-get update; \\",
                "    apt-get install -y --no-install-recommends mongodb-mongosh; \\",
                "    rm -rf /var/lib/apt/lists/* /tmp/mongodb.asc",
                "",
            ]
        )
    return lines


def tool_lines(configuration) -> list[str]:
    runtimes = configuration.runtimes
    php = runtimes.get("php")
    python = runtimes.get("python")
    node = runtimes.get("node")
    composer = configuration.tools.get("composer")
    lines = []
    if python:
        # Reinstall pip after relocating Python to regenerate executable shebangs.
        pip_version = configuration.tools.get("pip")
        requirement = (
            f"pip=={pip_version}"
            if pip_version
            else "\"pip==$(python -m pip --version | cut -d ' ' -f 2)\""
        )
        if pip_version or php:
            lines.extend(
                [
                    f"RUN python -m pip install --no-cache-dir --force-reinstall {requirement}",
                    "",
                ]
            )
        if uv := configuration.tools.get("uv"):
            lines.extend([f"RUN python -m pip install --no-cache-dir uv=={uv}", ""])
    if node:
        # Official Node images link Yarn outside /usr/local. It is installed
        # here only if selected, so remove these relocated, dangling links.
        lines.extend(["RUN rm -f /opt/node/bin/yarn /opt/node/bin/yarnpkg", ""])
    for tool in ("npm", "pnpm", "yarn"):
        if version := configuration.tools.get(tool):
            lines.extend([f"RUN npm install --global {tool}@{version}", ""])
    if composer:
        lines.extend(
            [
                "COPY --from=composer_binary /usr/bin/composer /usr/local/bin/composer",
                "",
            ]
        )
    for name in sorted(JAVA_TOOLS.keys() & configuration.tools.keys()):
        _, source, target, environment = JAVA_TOOLS[name]
        lines.append(f"COPY --from={name}_binary {source} {target}")
        lines.extend([f"ENV {value}" for value in environment] + [""])
    if playwright := configuration.tools.get("playwright"):
        lines.extend(
            [
                "ENV PLAYWRIGHT_BROWSERS_PATH=/opt/brig-playwright/browsers",
                "ENV NODE_PATH=/opt/node/lib/node_modules",
                f"RUN npm install --global playwright@{playwright} \\",
                "    && playwright install --with-deps chromium \\",
                "    && chmod -R a+rX /opt/brig-playwright \\",
                "    && rm -rf /var/lib/apt/lists/*",
                "",
            ]
        )
    return lines


def user_lines(composer) -> list[str]:
    lines = [
        "# Match these build arguments to the owner of the bind-mounted project folder.",
        "RUN set -eux; \\",
        '    groupadd --gid "$BRIG_GID" brig; \\',
        '    useradd --uid "$BRIG_UID" --gid brig --create-home --shell /bin/bash brig; \\',
        "    mkdir -p /workspace /home/brig/.config/composer /home/brig/.cache/composer /home/brig/.local/share /home/brig/.local/state; \\",
        "    chown -R brig:brig /workspace /home/brig",
        "",
    ]
    if composer:
        lines.extend(
            [
                "ENV COMPOSER_HOME=/home/brig/.config/composer \\",
                "    COMPOSER_CACHE_DIR=/home/brig/.cache/composer",
                "",
            ]
        )
    return lines
