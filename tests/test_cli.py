"""Command-level tests with isolated data and no interactive terminal."""

import io
import tempfile
import unittest
from contextlib import redirect_stderr, redirect_stdout
from pathlib import Path
from unittest.mock import patch

from brig.cli import main
from brig.application import Application
from brig.engine import DemoEngine
from brig.storage import JsonStateStore
from tests.fakes import FakeVersionCatalog, demo_state


class CliTests(unittest.TestCase):
    def setUp(self):
        self.directory = tempfile.TemporaryDirectory()
        self.addCleanup(self.directory.cleanup)
        self.data = Path(self.directory.name) / "data"
        fake_engine = patch("brig.cli.DockerEngine", return_value=DemoEngine())
        fake_engine.start()
        self.addCleanup(fake_engine.stop)

    def command(self, *arguments):
        output, errors = io.StringIO(), io.StringIO()
        with redirect_stdout(output), redirect_stderr(errors):
            status = main(["--data-dir", str(self.data), *arguments])
        return status, output.getvalue(), errors.getvalue()

    def test_list_show_and_demo_execution(self):
        JsonStateStore(self.data).save(demo_state())
        status, output, errors = self.command("profile", "list")
        self.assertEqual(status, 0)
        self.assertIn("web_dev", output)
        self.assertEqual(errors, "")
        status, output, _ = self.command("project", "show", "website")
        self.assertEqual(status, 0)
        self.assertIn("no folder mounted", output)
        self.assertIn("not created", output)
        status, output, _ = self.command("up", "--project", "website")
        self.assertEqual(status, 0)
        self.assertIn("simulated", output)
        status, output, _ = self.command("agent", "claude", "--project", "website")
        self.assertEqual(status, 0)
        self.assertIn("no agent was launched", output)
        self.assertEqual(self.command("shell", "--project", "website")[0], 0)
        self.assertEqual(self.command("down", "--project", "website")[0], 0)

    def test_dockerfile_stdout_is_a_recipe_without_demo_banner(self):
        JsonStateStore(self.data).save(demo_state())
        status, output, errors = self.command("project", "dockerfile", "website")
        self.assertEqual(status, 0)
        self.assertTrue(output.startswith("# Generated by Brig"))
        self.assertIn("FROM php:8.3.15-cli-bookworm", output)
        self.assertNotIn("brig · Demo mode", output)
        self.assertEqual(errors, "")

    def test_run_selects_one_project_and_passes_command_arguments(self):
        JsonStateStore(self.data).save(demo_state())
        engine = DemoEngine()
        with (
            patch("brig.cli.DockerEngine", return_value=engine),
            patch.object(engine, "shell", return_value="") as shell,
        ):
            status, output, errors = self.command(
                "run", "website", "--command", "python", "-c", "print('$HOME')"
            )
        self.assertEqual(status, 0)
        self.assertEqual((output, errors), ("", ""))
        self.assertEqual(shell.call_args.args[0].name, "website")
        self.assertEqual(shell.call_args.args[1], ["python", "-c", "print('$HOME')"])
        self.assertTrue(JsonStateStore(self.data).load().projects[0].running)

    def test_run_rejects_conflicting_projects_or_empty_command(self):
        JsonStateStore(self.data).save(demo_state())
        for arguments, message in (
            (("run", "website", "--project", "api"), "Choose one project"),
            (("run", "website", "--command"), "needs a program"),
        ):
            status, _, errors = self.command(*arguments)
            self.assertEqual(status, 1)
            self.assertIn(message, errors)

    def test_dockerfile_export_and_python_project(self):
        JsonStateStore(self.data).save(demo_state())
        output = Path(self.directory.name) / "Dockerfile"
        status, message, errors = self.command(
            "project", "dockerfile", "website", "--output", str(output)
        )
        self.assertEqual(status, 0)
        self.assertIn(str(output), message)
        self.assertIn("FROM composer:2.8.5", output.read_text())
        self.assertEqual(errors, "")
        status, _, errors = self.command(
            "project", "dockerfile", "website", "--output", str(output)
        )
        self.assertEqual(status, 1)
        self.assertIn("already exists", errors)
        status, contents, errors = self.command("project", "dockerfile", "api")
        self.assertEqual(status, 0)
        self.assertIn("FROM python:", contents)
        self.assertNotIn("FROM php:", contents)
        self.assertEqual(errors, "")

    def test_dockerfile_can_resolve_project_from_its_folder(self):
        app = Application(JsonStateStore(self.data), DemoEngine(), FakeVersionCatalog)
        app.save_profile("laravel", {"php": "8.3.15"}, {}, {})
        folder = Path(self.directory.name) / "source"
        folder.mkdir()
        app.create_project("laravel_project", folder, "laravel")
        with patch("brig.cli.Path.cwd", return_value=folder):
            status, output, errors = self.command("project", "dockerfile")
        self.assertEqual(status, 0)
        self.assertIn("FROM php:8.3.15-cli-bookworm", output)
        self.assertEqual(errors, "")

    def test_project_resolution_error_is_actionable(self):
        with patch("brig.cli.Path.cwd", return_value=Path(self.directory.name)):
            status, _, errors = self.command("up")
        self.assertEqual(status, 1)
        self.assertIn("--project", errors)

    def test_future_agent_returns_error(self):
        JsonStateStore(self.data).save(demo_state())
        status, _, errors = self.command("agent", "codex", "--project", "api")
        self.assertEqual(status, 1)
        self.assertIn("future integration", errors)

    def test_delete_with_explicit_confirmation_removes_unused_profile(self):
        app = Application(JsonStateStore(self.data), DemoEngine(), FakeVersionCatalog)
        app.save_profile("custom", {"php": "8.3.15"}, {}, {})
        status, output, errors = self.command("profile", "delete", "custom", "--yes")
        self.assertEqual(status, 0)
        self.assertIn("Deleted profile 'custom'", output)
        self.assertEqual(errors, "")
        self.assertNotIn("custom", self.command("profile", "list")[1])

    def test_delete_used_profile_is_rejected_even_with_yes(self):
        JsonStateStore(self.data).save(demo_state())
        status, _, errors = self.command("profile", "delete", "web_dev", "--yes")
        self.assertEqual(status, 1)
        self.assertIn("Used by projects: website", errors)
        self.assertIn("web_dev", self.command("profile", "list")[1])

    def test_project_delete_with_yes_keeps_folder_and_profile_yaml(self):
        app = Application(JsonStateStore(self.data), DemoEngine(), FakeVersionCatalog)
        app.save_profile("custom", {"php": "8.3.15"}, {}, {})
        folder = Path(self.directory.name) / "source"
        folder.mkdir()
        source = folder / "index.php"
        source.write_text("<?php echo 'hello';")
        app.create_project("custom_project", folder, "custom")
        before = {path: path.read_bytes() for path in self.data.rglob("*.yaml")}
        status, output, errors = self.command(
            "project", "delete", "custom_project", "--yes"
        )
        self.assertEqual(status, 0)
        self.assertIn("Deleted project 'custom_project'", output)
        self.assertEqual(errors, "")
        self.assertTrue(source.exists())
        self.assertEqual(
            {path: path.read_bytes() for path in self.data.rglob("*.yaml")}, before
        )
        self.assertEqual(JsonStateStore(self.data).load().projects, [])

    def test_project_delete_with_yes_cannot_delete_running_project(self):
        JsonStateStore(self.data).save(demo_state())
        status, _, errors = self.command("project", "delete", "api", "--yes")
        self.assertEqual(status, 1)
        self.assertIn("brig down --project api", errors)
        self.assertIn("api", self.command("project", "list")[1])

    def test_first_run_lists_are_empty_and_remain_empty_on_reload(self):
        for _ in range(2):
            status, output, errors = self.command("profile", "list")
            self.assertEqual(status, 0)
            self.assertIn("No profiles.", output)
            self.assertEqual(errors, "")
            self.assertIn("No projects.", self.command("project", "list")[1])
        self.assertEqual(JsonStateStore(self.data).load().profiles, [])
        self.assertEqual(JsonStateStore(self.data).load().projects, [])

    def test_noninteractive_wizards_fail_without_initializing_data(self):
        for arguments in (
            (),
            ("profile", "create"),
            ("profile", "edit", "web_dev"),
            ("profile", "delete", "web_dev"),
            ("project", "init"),
            ("project", "delete", "website"),
        ):
            with (
                self.subTest(arguments=arguments),
                patch("sys.stdin.isatty", return_value=False),
            ):
                status, _, errors = self.command(*arguments)
            self.assertEqual(status, 2)
            self.assertIn("interactive terminal", errors)
            self.assertFalse(self.data.exists())

    def test_invalid_data_is_not_replaced_by_command(self):
        self.data.mkdir()
        file = self.data / "state.json"
        file.write_text("broken")
        status, _, errors = self.command("project", "list")
        self.assertEqual(status, 1)
        self.assertIn("File was not changed", errors)
        self.assertEqual(file.read_text(), "broken")
